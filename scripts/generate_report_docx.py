def clean_markdown_for_word(text: str) -> str:
    """Remove anchor links and horizontal rules, normalize whitespace."""
    lines: list[str] = []
    for line in text.splitlines():
        line = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", line)
        if line.strip() in ("---", "***", "___"):
            continue
        lines.append(line)
    body = "\n".join(lines)
    body = re.sub(r"\n{3,}", "\n\n", body)
    return body.strip() + "\n"


